"""Тексты для фичи /who."""


def who_result_text(user_display: str, members_count: int) -> str:
    return (
        f"🎲 <b>Квантовая Вселенная сделала выбор!</b>\n\n"
        f"👉 {user_display}\n\n"
        f"📊 Участников в пуле: {members_count}\n"
        f"⚛️ Выбор основан на квантовой случайности ANU QRNG."
    )


def who_not_group_text() -> str:
    return (
        "⚠️ Команда /who работает только в групповых чатах!\n"
        "Добавь бота в группу и попробуй снова."
    )


def who_no_members_text() -> str:
    return (
        "😔 Пока не удалось определить участников.\n"
        "Попросите кого-нибудь написать сообщение в чат, "
        "чтобы бот запомнил участников, и попробуйте снова."
    )


def who_error_text() -> str:
    return "⚠️ Произошла ошибка при выборе участника. Попробуй позже."